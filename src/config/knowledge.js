// ── 키워드 매칭 ────────────────────────────────────────────────
const questionTokens = (q) => norm(q).split(' ').filter((w) => w.length >= 2)

export function scoreEntry(entry, text) {
  const t = norm(text)
  if (!t) return 0
  const hasMineral = MINERAL_HINTS.some((h) => hit(t, h))
  const hasEnzyme = ENZYME_HINTS.some((h) => hit(t, h))

  let kwScore = 0
  let kwHits = 0
  for (const kw of entry.keywords) {
    const k = norm(kw)
    if (!k) continue
    if (BRAND.some((b) => norm(b) === k)) {
      // 브랜드·상품군 이름만으로는 답을 고르지 않고, 어느 제품군인지 표시만 더합니다.
      if (hit(t, k)) kwScore += 0.4
      continue
    }
    if (hit(t, k)) {
      kwScore += weight(k)
      kwHits += 1
    }
  }
  if (kwHits === 0) return 0

  let score = kwScore

  // 질문 문장과 겹치는 말 (보조 신호)
  let overlap = 0
  for (const tok of questionTokens(entry.question)) {
    if (t.includes(tok)) overlap += 0.4
  }
  score += Math.min(1.6, overlap)

  // 상품군 일치 보정 — 같은 상품 이야기면 앞세우고, 다른 상품 이야기면 뒤로 뺍니다.
  if (entry.group === 'mineral') {
    if (hasMineral) score += 4
    else if (hasEnzyme) score -= 4
  } else if (entry.group === 'enzyme') {
    if (hasEnzyme) score += 4
    else if (hasMineral) score -= 4
  }
  return score
}

// 가장 잘 맞는 지식베이스 항목 (없으면 null → 상담원이 '모르겠다'고 답합니다)
export function matchKnowledge(text, { minScore = 1.6 } = {}) {
  let best = null
  let bestScore = 0
  for (const entry of knowledge) {
    const s = scoreEntry(entry, text)
    if (s > bestScore) {
      best = entry
      bestScore = s
    }
  }
  return bestScore >= minScore ? { entry: best, score: bestScore } : null
}

export const knowledgeById = (id) => knowledge.find((e) => e.id === id)
