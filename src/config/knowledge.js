const hit = (t, phrase) => {
  const k = norm(phrase)
  if (!k) return false
  if (k.length <= 1) return new RegExp(`(^|\\s)${escapeRe(k)}`).test(t)
  return t.includes(k)
}

const weight = (phrase) => {
  const k = norm(phrase)
  const base = 1 + Math.min(2.5, 0.35 * k.length)
  return k.includes(' ') ? base + 0.8 : base
}

